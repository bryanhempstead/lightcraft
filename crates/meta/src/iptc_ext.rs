//! IPTC Extension (and PLUS licensing) fields Lightroom Classic shows in its Metadata panel's
//! "IPTC Extension" view (L21): Person Shown, Event, model / property releases, Digital Source
//! Type, organisations, model age and information. Read from and written to XMP; values are text,
//! a list kept as one text with `; ` between the items.

/// How a field is written in XMP.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExtKind {
    /// A simple property (a URI from a controlled vocabulary for the status fields).
    Text,
    /// A language alternative (`rdf:Alt`, `x-default`).
    Alt,
    /// An unordered list (`rdf:Bag`): `; ` between the items.
    Bag,
}

/// One IPTC Extension field.
#[derive(Clone, Copy, Debug)]
pub struct ExtField {
    /// Its id in commands and the catalog (`personShown`).
    pub id: &'static str,
    /// The XMP property (`Iptc4xmpExt:PersonInImage`).
    pub prop: &'static str,
    /// Lightroom's name for it.
    pub label: &'static str,
    pub kind: ExtKind,
    /// A controlled vocabulary: (value written, name shown); empty = free text.
    pub choices: &'static [(&'static str, &'static str)],
    /// Says something about the people in the photo (left out by an export's Remove Person Info).
    pub person: bool,
}

