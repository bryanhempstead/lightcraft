/// The field with this id.
pub fn field(id: &str) -> Option<&'static ExtField> {
    IPTC_EXT.iter().find(|f| f.id == id)
}

/// A value as stored: trimmed; a list's items trimmed, empty ones dropped, `; ` between them; a
/// vocabulary field accepts its value, its name (any case) or the code at the end of the URI
/// (`MR-NON`, `digitalCapture`). `Err` says why a value can't be used.
pub fn normalise(f: &ExtField, value: &str) -> Result<String, String> {
    let v = value.trim();
    if v.chars().count() > 2000 {
        return Err(format!("{}: at most 2000 characters", f.label));
    }
    if v.chars().any(|c| c.is_control() && c != '\n') {
        return Err(format!("{}: control characters", f.label));
    }
    if v.is_empty() {
        return Ok(String::new());
    }
    if !f.choices.is_empty() {
        return f
            .choices
            .iter()
            .find(|(uri, name)| {
                uri.eq_ignore_ascii_case(v) || name.eq_ignore_ascii_case(v) || uri.rsplit('/').next().is_some_and(|c| c.eq_ignore_ascii_case(v))
            })
            .map(|(uri, _)| uri.to_string())
            .ok_or_else(|| format!("{}: one of {}", f.label, f.choices.iter().map(|c| c.1).collect::<Vec<_>>().join(", ")));
    }
    if f.kind == ExtKind::Bag {
        return Ok(items(v).join("; "));
    }
    Ok(v.to_string())
}

/// A list value's items.
pub fn items(v: &str) -> Vec<String> {
    v.split(';').map(str::trim).filter(|s| !s.is_empty()).map(str::to_string).collect()
}

/// The name shown for a stored value (a vocabulary's name, else the value).
pub fn display(f: &ExtField, v: &str) -> String {
    f.choices.iter().find(|c| c.0 == v).map(|c| c.1.to_string()).unwrap_or_else(|| v.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vocabularies_and_lists_are_normalised() {
        let mr = field("modelReleaseStatus").unwrap();
        assert_eq!(normalise(mr, "mr-non").unwrap(), "http://ns.useplus.org/ldf/vocab/MR-NON");
        assert_eq!(normalise(mr, "Not Applicable").unwrap(), "http://ns.useplus.org/ldf/vocab/MR-NAP");
        assert!(normalise(mr, "maybe").is_err());
        let ds = field("digitalSourceType").unwrap();
        assert!(normalise(ds, "digitalCapture").unwrap().ends_with("/digitalCapture"));
        let ps = field("personShown").unwrap();
        assert_eq!(normalise(ps, " Ann ;; Bo ; ").unwrap(), "Ann; Bo");
        assert_eq!(normalise(ps, "  ").unwrap(), "");
        assert!(normalise(ps, "a\u{0}b").is_err());
        assert!(normalise(ps, &"x".repeat(3000)).is_err());
        assert_eq!(display(mr, "http://ns.useplus.org/ldf/vocab/MR-NON"), "None");
    }
}
