//! Measured with our Camera Raw oracle (`oracle/make_fx.py mask2`: a linear-gradient mask covering
//! the spatial scene at three brightnesses, each slider at ±50 / ±100; `local_ana.py` reads the
//! scene-referred log2 change by level off the scene's gradient through LightCraft's own base,
//! `gen_local.py` writes the tables). Camera Raw's local sliders are curves of the scene level,
//! the same on a scene 2 EV darker or 1 EV brighter (not relative to the photo), and unlike the
