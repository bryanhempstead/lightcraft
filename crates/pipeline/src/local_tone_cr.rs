/// log2 change of `table` at amount `a` (−1..1) and scene level `l1` (log2 of Y / 0.18).
#[inline]
pub fn at(table: &[[f32; KNOTS]; 4], a: f32, l1: f32) -> f32 {
    if a == 0.0 || !a.is_finite() || !l1.is_finite() {
        return 0.0;
    }
    let f = ((l1 - KNOT0) / KNOT_STEP).clamp(0.0, (KNOTS - 1) as f32);
    let i = (f as usize).min(KNOTS - 2);
    let t = f - i as f32;
    let row = |r: usize| table[r][i] + (table[r][i + 1] - table[r][i]) * t;
    let a = a.clamp(-1.0, 1.0);
    match a {
        a if a <= -0.5 => row(1) + (row(0) - row(1)) * (-a - 0.5) / 0.5,
        a if a < 0.0 => row(1) * (-a / 0.5),
        a if a <= 0.5 => row(2) * (a / 0.5),
        a => row(2) + (row(3) - row(2)) * (a - 0.5) / 0.5,
    }
}

/// The three tables flattened for the GPU kernel (Contrast, Whites, Blacks; amounts −100, −50,
/// +50, +100; [`KNOTS`] levels each).
pub fn words() -> Vec<f32> {
    [CONTRAST, WHITES, BLACKS].iter().flatten().flatten().copied().collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_blacks_lift_the_deep_shadows_most() {
        assert!(at(&BLACKS, 0.5, -5.0) > 2.0 && at(&BLACKS, 0.5, 1.0) < 0.3);
        assert!(at(&BLACKS, -0.5, -3.0) < -2.0);
        assert!((at(&BLACKS, 0.25, -5.0) - 0.5 * at(&BLACKS, 0.5, -5.0)).abs() < 1e-6);
        assert_eq!(at(&WHITES, 0.0, 0.0), 0.0);
        assert_eq!(at(&CONTRAST, f32::NAN, 0.0), 0.0);
        // Contrast + darkens below its pivot and brightens above it
        assert!(at(&CONTRAST, 1.0, -3.0) < 0.0 && at(&CONTRAST, 1.0, 1.0) > 0.0);
        assert_eq!(words().len(), 3 * 4 * KNOTS);
    }
}
