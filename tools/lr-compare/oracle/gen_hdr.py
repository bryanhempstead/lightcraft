"""gen_hdr.py gtables.npz OUT.rs: write crates/pipeline/src/tone_hdr.rs's tables from fit.py's output.
Gaps are filled: g0 past its last measured point continues at its last slope; a slider's delta
holds its last measured value past its range and is linear in the slider between measured values."""
import sys, numpy as np
z = np.load(sys.argv[1])
D, g0 = z["D"], z["g0"].copy()


def fill(t, extend_slope):
    t = t.copy()
    ok = np.where(np.isfinite(t))[0]
    if len(ok) == 0:
        return np.zeros_like(t)
    lo, hi = ok[0], ok[-1]
    t[:lo] = t[lo]
    if extend_slope and hi >= 2:
        s = (t[hi] - t[hi - 2]) / 2
        for i in range(hi + 1, len(t)):
            t[i] = t[hi] + s * (i - hi)
    else:
        t[hi + 1:] = t[hi]
    # interior gaps: linear
    idx = np.arange(len(t))
    bad = ~np.isfinite(t)
    t[bad] = np.interp(idx[bad], idx[~bad], t[~bad])
    return t


g0 = fill(g0, True)
# midtones are the SDR rendition's (Camera Raw: identical below about 0.4 of SDR white)
g0[D <= -0.25] = 0.0
def vals(p):
    return sorted(int(k[1:]) for k in z.files if k.startswith(p) and np.isfinite(z[k]).any())


# Highlights and Blacks: measured (h*/b* in the fit) but left out. Camera Raw's HDR shadows and
# midtones are its SDR ones under both (sdr_* twins); above, Highlights' ramp deltas did not carry
# over to real photos (hdr4_hl-60 5.6 → 6.8 ΔEITP with them) and Blacks' are under 0.01 EV
ws, cs = vals("w"), vals("c")


def smooth3(t):
    p = np.r_[t[0], t, t[-1]]
    return (p[:-2] + 2 * p[1:-1] + p[2:]) / 4


def delta(k):
    t = smooth3(smooth3(fill(z[k], False)))
    return t


def rs(a):
    return "[" + ", ".join(f"{v:.4f}" for v in a) + "]"


out = f"""//! Camera Raw's HDR tone (Bryan's fork, `docs/lr-match.md` → HDR tone), measured with Camera Raw
//! itself: synthetic LinearRaw ramps with HDR on, rendered by Camera Raw in Photoshop (Rec. 2100 PQ,
//! SDR white = 203 nits) against LightCraft's SDR tone of the same settings. Generated by
//! `tools/lr-compare/oracle/gen_hdr.py`; do not edit by hand. Applied by [`crate::tone_hdr`].
//!
//! Camera Raw's HDR render is the SDR one below about 0.4 of SDR white, then opens up much faster
//! than the SDR shoulder (about 1.5 stops out per stop in, an expanding curve) and is cut hard at
//! the HDR Limit; the curve itself does not depend on the limit, and Exposure moves the scene
//! along it as a plain gain. As a table: the HDR output is the SDR tone times `2^g`, `g` per EV
//! past where the SDR tone reaches 0.5 (`D0` in steps of `STEP`), plus Whites' and Contrast's own
//! HDR effect (deltas at the measured slider values, linear in between, 0 at 0).

pub const D0: f32 = {D[0]:.2f};
pub const STEP: f32 = {D[1] - D[0]:.2f};
pub const N: usize = {len(D)};
pub const G0: [f32; N] = {rs(g0)};
pub const W_VALUES: [f32; {len(ws)}] = [{", ".join(f"{w:.1f}" for w in ws)}];
pub const W_TABLE: [[f32; N]; {len(ws)}] = [{", ".join(rs(delta(f"w{w}")) for w in ws)}];
pub const C_VALUES: [f32; {len(cs)}] = [{", ".join(f"{c:.1f}" for c in cs)}];
pub const C_TABLE: [[f32; N]; {len(cs)}] = [{", ".join(rs(delta(f"c{c}")) for c in cs)}];
"""
open(sys.argv[2], "w").write(out)
print(ws, cs)
