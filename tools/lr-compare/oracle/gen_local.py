"""gen_local.py SET LCDIR > local_tone_cr tables: the masks' local Contrast / Whites / Blacks curves
(R16) as Camera Raw renders them, read off the spatial scenes of `make_fx.py mask2` with
`local_ana.py`'s inversion through LightCraft's own base (scene-referred log2 change by
l1 = log2(Y / 0.18)), averaged over the three scene brightnesses where measured, the ends held
(dark / bright levels Camera Raw clips past LightCraft's base) or continued with the last slope
(Blacks below its measured range), and printed as the Rust table for
`crates/pipeline/src/local_tone_cr.rs`."""
import sys, os, subprocess, json, numpy as np

S, L = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
SL = {"Con": [-100, -50, 50, 100], "Whi": [-100, -50, 50, 100], "Bla": [-100, -50, 50, 100]}
items = [f"l{k}{v:+d}" for k, vs in SL.items() for v in vs]
data = {}
for sc in ("spatial", "spatialD", "spatialB"):
    out = f"/tmp/local_{os.getpid()}_{sc}.json"
    subprocess.run([sys.executable, f"{HERE}/local_ana.py", S, L, *items, f"--json={out}"], env=dict(os.environ, SCENE=sc), check=True, capture_output=True)
    d = json.load(open(out)); os.remove(out)
    knots = d["knots"]
    for it, v in d["items"].items():
        data.setdefault(it, []).append(np.array(v["acr"], dtype=float))
K = np.array(knots)


def fill(v, slope_low):
    v = v.copy()
    ok = np.isfinite(v)
    if not ok.any():
        return np.zeros_like(v)
    i0, i1 = np.argmax(ok), len(v) - 1 - np.argmax(ok[::-1])
    # interior gaps: interpolate
    v = np.interp(np.arange(len(v)), np.where(ok)[0], v[ok])
    if slope_low and i0 + 1 <= i1:
        s = v[i0 + 1] - v[i0]
        for i in range(i0 - 1, -1, -1):
            v[i] = max(v[i + 1] - s, -4.0) if s > 0 else v[i + 1]
    return v


rows = {}
for k, vs in SL.items():
    rows[k] = []
    for a in vs:
        stack = np.array(data[f"l{k}{a:+d}"])
        v = np.nanmean(stack, 0) if np.isfinite(stack).any() else np.zeros(len(K))
        # Whites: the toe below −4 EV is the inversion's noise (Whites barely reach there)
        if k == "Whi":
            v[K < -3.5] = np.nan
        if k == "Con":
            v[K < -4.0] = np.nan
        rows[k].append(fill(v, slope_low=(k == "Bla" and a < 0)))
print(f"// generated by tools/lr-compare/oracle/gen_local.py from {os.path.basename(S)} (Camera Raw oracle)")
print(f"pub const KNOT0: f32 = {K[0]:.1f};\npub const KNOT_STEP: f32 = {K[1] - K[0]:.1f};\npub const KNOTS: usize = {len(K)};")
print("pub const AMOUNTS: [f32; 4] = [-1.0, -0.5, 0.5, 1.0];")
for k, name in (("Con", "CONTRAST"), ("Whi", "WHITES"), ("Bla", "BLACKS")):
    print("#[rustfmt::skip]")
    print(f"pub const {name}: [[f32; KNOTS]; 4] = [")
    for r in rows[k]:
        print("    [" + ", ".join(f"{x:.3f}" for x in r) + "],")
    print("];")
